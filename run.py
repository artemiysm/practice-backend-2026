"""
Точка входа в приложение Flask.

Запускает веб-сервер в режиме разработки с включенным отладчиком.
При запуске инициализируются:
- База данных (db)
- Миграции (migrate)
- Система аутентификации (JWT)
"""

from app import create_app
from app.extensions import db, migrate

app = create_app()

if __name__ == '__main__':
    # Повторная инициализация расширений для контекста CLI
    # (необходимо для работы flask-migrate и других команд)
    db.init_app(app)
    migrate.init_app(app, db)
    
    # Запуск встроенного сервера разработки
    # debug=True включает:
    # - Автоперезагрузку при изменении кода
    # - Интерактивный отладчик в браузере
    # - Подробные сообщения об ошибках
    app.run(debug=True, host='0.0.0.0', port=5000)